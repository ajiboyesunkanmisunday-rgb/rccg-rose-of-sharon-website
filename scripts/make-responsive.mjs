#!/usr/bin/env node
/*
 * Makes phone- and tablet-sized WebP copies of the big pictures in packages/shared/public, so a phone downloads a
 * 40-90 KB picture instead of the 250-450 KB desktop one. Writes name.w480.webp / .w800.webp / .w1200.webp next to each
 * picture, plus packages/shared/src/responsive.ts (which pictures have which sizes). Run it again after adding pictures:
 *   node scripts/make-responsive.mjs
 * Pictures that already have their copies are skipped. Needs `sharp` (already installed with Next.js).
 */
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const pool = path.join(root, "packages/shared/public");
const WIDTHS = [480, 800, 1200];
const MIN_BYTES = 60_000;
const SKIP = [/^css\//, /^marketplace\//];

const manifest = {};
function* walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) yield* walk(p);
    else yield p;
  }
}

let made = 0;
for (const file of walk(pool)) {
  const rel = path.relative(pool, file).split(path.sep).join("/");
  if (!/\.(jpe?g|png)$/i.test(rel) || /\.w\d+\.webp$/.test(rel) || SKIP.some((r) => r.test(rel))) continue;
  if (fs.statSync(file).size < MIN_BYTES) continue;
  const meta = await sharp(file).metadata();
  const w = meta.width ?? 0;
  const widths = WIDTHS.filter((x) => x < w * 0.9);
  if (!widths.length) continue;
  const base = file.replace(/\.[^.]+$/, "");
  for (const x of widths) {
    const out = `${base}.w${x}.webp`;
    if (fs.existsSync(out)) continue;
    await sharp(file).resize({ width: x }).webp({ quality: 72, effort: 5 }).toFile(out);
    made++;
  }
  manifest[rel] = [w, widths];
}

const body = Object.keys(manifest).sort().map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(manifest[k])},`).join("\n");
fs.writeFileSync(
  path.join(root, "packages/shared/src/responsive.ts"),
  `// Generated by scripts/make-responsive.mjs - do not edit. picture path (no leading slash) -> [original width, phone/tablet widths]\n` +
  `export const RESPONSIVE: Record<string, [number, number[]]> = {\n${body}\n};\n`
);
console.log(`${Object.keys(manifest).length} pictures, ${made} new copies`);
